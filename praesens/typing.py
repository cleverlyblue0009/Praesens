"""Milestone 10: typing lane (ACTIVE + PASSIVE).

PRIVACY -- read this before touching the keystroke capture code below.
This module retains keystroke TIMING ONLY: inter-key intervals, key-down/
key-up perf_counter() timestamps, and a per-character boolean
matched_expected (ACTIVE mode -- did this keystroke match the next
expected character of the session's challenge phrase?). It NEVER stores,
logs, returns, or serialises the pressed character, the phrase as actually
typed, clipboard content, or window titles. The pressed character exists
only as a local variable inside KeystrokeCapture._on_press, used for a
single equality comparison against the expected phrase, and goes out of
scope the instant that function returns -- it is never appended to
KeystrokeCapture.events or any other structure that outlives the callback.
This is the single line between this project and a keylogger, and it is a
claim made in the patent disclosure. Do not weaken it: if you find yourself
wanting to store, print, or return the character for debugging, don't --
matched_expected (a boolean) is the only signal this module is allowed to
carry about WHAT was typed.

ACTIVE mode displays a session-unique challenge phrase (generated by
praesens.challenge.generate_challenge_phrase) and verifies keystrokes
against it, plus checks keystroke timing against camera-observed hand
motion. PASSIVE mode drops the phrase entirely and checks ONLY keystroke-
hand coherence on whatever the operator naturally types -- there is no
expected sequence to compare against, so matched_expected is always None
in PASSIVE mode. Confidence decays with time since the last keystroke;
sustained silence triggers a re-challenge rather than silently degrading
to a stale verdict.

Hand-motion coherence uses MediaPipe's HandLandmarker on the SAME camera
stream the optical lane already has open -- callers integrating this lane
must feed frames in rather than opening a second cv2.VideoCapture, since
opening two capture handles to one physical camera is unreliable at best
on most drivers (see also demo/attack.py's own reasoning for pre-opening
capture handles instead of reopening them).
"""
from __future__ import annotations

import threading
import time
from collections import Counter, deque
from dataclasses import dataclass, field
from pathlib import Path

import numpy as np
from pynput import keyboard

from mediapipe.tasks.python import vision as mp_vision
from mediapipe.tasks.python import BaseOptions


# ---------------------------------------------------------------------------
# Keystroke timing capture -- see module docstring for the privacy contract.
# ---------------------------------------------------------------------------

class KeystrokeCapture:
    """expected_phrase=None runs in PASSIVE mode: no cursor, no matching,
    matched_expected is always None. expected_phrase=<str> runs ACTIVE:
    each printable keypress is compared against the next expected
    character (only the BOOLEAN result is kept, see module docstring)."""

    def __init__(self, expected_phrase: str | None = None):
        self.expected_phrase = expected_phrase
        self._cursor = 0
        self.events: list[dict] = []  # {"t_down","t_up","matched_expected"} ONLY -- no characters, ever
        self._open_indices: deque = deque()
        self._lock = threading.Lock()
        self._listener: keyboard.Listener | None = None

    @property
    def phrase_complete(self) -> bool:
        return self.expected_phrase is not None and self._cursor >= len(self.expected_phrase)

    @staticmethod
    def _extract_char_local(key):
        """Local-scope-only: the return value is used for ONE comparison
        by the caller and must never be stored, logged, or returned
        further up the call stack (see module docstring)."""
        if key == keyboard.Key.space:
            return " "
        return getattr(key, "char", None)

    def _on_press(self, key) -> None:
        t = time.perf_counter()
        pressed_char = self._extract_char_local(key)  # local only
        matched = None
        if self.expected_phrase is not None and pressed_char is not None and not self.phrase_complete:
            expected_char = self.expected_phrase[self._cursor]
            matched = (pressed_char == expected_char)
            if matched:
                self._cursor += 1
        with self._lock:
            self.events.append({"t_down": t, "t_up": None, "matched_expected": matched})
            self._open_indices.append(len(self.events) - 1)
        # pressed_char and key fall out of scope here; nothing further
        # references either, so no persisted structure ever holds them.

    def _on_release(self, key) -> None:
        t = time.perf_counter()
        with self._lock:
            if self._open_indices:
                idx = self._open_indices.popleft()  # FIFO pairing, approximate but privacy-safe
                self.events[idx]["t_up"] = t

    def start(self) -> None:
        self._listener = keyboard.Listener(on_press=self._on_press, on_release=self._on_release)
        self._listener.start()

    def stop(self) -> None:
        if self._listener is not None:
            self._listener.stop()
            self._listener = None

    def get_events(self) -> list[dict]:
        with self._lock:
            return [dict(e) for e in self.events]

    def last_keystroke_time(self) -> float | None:
        events = self.get_events()
        return max((e["t_down"] for e in events), default=None)

    def inter_key_intervals(self) -> np.ndarray:
        events = self.get_events()
        if len(events) < 2:
            return np.array([])
        t_downs = np.array([e["t_down"] for e in events])
        return np.diff(t_downs)


