"""Milestone 10: typing lane (ACTIVE + PASSIVE).

PRIVACY -- read this before touching the keystroke capture code below.
This module retains keystroke TIMING ONLY: inter-key intervals, key-down/
key-up perf_counter() timestamps, and a per-character boolean
matched_expected (ACTIVE mode -- did this keystroke match the next
expected character of the session's challenge phrase?). It NEVER stores,
logs, returns, or serialises the pressed character, the phrase as actually
typed, clipboard content, or window titles. The pressed character exists
only as a local variable inside KeystrokeCapture._on_press, used for a
single equality comparison against the expected phrase, and goes out of
scope the instant that function returns -- it is never appended to
KeystrokeCapture.events or any other structure that outlives the callback.
This is the single line between this project and a keylogger, and it is a
claim made in the patent disclosure. Do not weaken it: if you find yourself
wanting to store, print, or return the character for debugging, don't --
matched_expected (a boolean) is the only signal this module is allowed to
carry about WHAT was typed.

ACTIVE mode displays a session-unique challenge phrase (generated by
praesens.challenge.generate_challenge_phrase) and verifies keystrokes
against it, plus checks keystroke timing against camera-observed hand
motion. PASSIVE mode drops the phrase entirely and checks ONLY keystroke-
hand coherence on whatever the operator naturally types -- there is no
expected sequence to compare against, so matched_expected is always None
in PASSIVE mode. Confidence decays with time since the last keystroke;
sustained silence triggers a re-challenge rather than silently degrading
to a stale verdict.

Hand-motion coherence uses MediaPipe's HandLandmarker on the SAME camera
stream the optical lane already has open -- callers integrating this lane
must feed frames in rather than opening a second cv2.VideoCapture, since
opening two capture handles to one physical camera is unreliable at best
on most drivers (see also demo/attack.py's own reasoning for pre-opening
capture handles instead of reopening them).
"""
