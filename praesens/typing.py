def _derive_fingertip_index(connections_finger, connections_palm) -> int:
    """Same technique as praesens/optical.py's ROI derivation: pull the
    index from MediaPipe's own connection sets rather than a memorised
    landmark number. A finger's connection chain has exactly two degree-1
    nodes -- the base (MCP, which also appears in the palm connections)
    and the tip (which appears nowhere else). The one NOT in the palm set
    is the tip."""
    deg = Counter()
    for c in connections_finger:
        deg[c.start] += 1
        deg[c.end] += 1
    degree_one = [n for n, d in deg.items() if d == 1]
    palm_nodes = set()
    for c in connections_palm:
        palm_nodes.add(c.start)
        palm_nodes.add(c.end)
    tip_candidates = [n for n in degree_one if n not in palm_nodes]
    if len(tip_candidates) != 1:
        raise ValueError(f"expected exactly one fingertip candidate, got {tip_candidates}")
    return tip_candidates[0]


_HLC = mp_vision.HandLandmarksConnections
INDEX_FINGERTIP_IDX = _derive_fingertip_index(_HLC.HAND_INDEX_FINGER_CONNECTIONS, _HLC.HAND_PALM_CONNECTIONS)


def create_hand_landmarker(model_path: str, running_mode=mp_vision.RunningMode.VIDEO,
                            min_confidence: float = 0.5):
    model_path = Path(model_path)
    if not model_path.exists():
        raise FileNotFoundError(
            f"HandLandmarker model not found at {model_path}. Run "
            f"'python scripts/fetch_model.py --hand' once to download it."
        )
    options = mp_vision.HandLandmarkerOptions(
        base_options=BaseOptions(model_asset_path=str(model_path)),
        running_mode=running_mode,
        num_hands=2,
        min_hand_detection_confidence=min_confidence,
        min_hand_presence_confidence=min_confidence,
        min_tracking_confidence=min_confidence,
    )
    return mp_vision.HandLandmarker.create_from_options(options)


class HandActivityTracker:
    """Turns HandLandmarker results into a scalar "how much is the hand
    moving right now" signal: index-fingertip displacement magnitude from
    the previous DETECTED frame, summed over however many hands are
    visible. Genuine typing produces bursts of this signal roughly
    synchronised with keystrokes; an injected video's hands (if visible at
    all) move on their own unrelated schedule."""

    def __init__(self):
        self._last_positions: dict[int, np.ndarray] = {}

    def process(self, result) -> float:
        """NaN if no hand detected this frame -- caller should treat a
        session with too few non-NaN samples as no_evidence, not score it
        as zero (rule 7: a lane that can't produce evidence says so)."""
        if not result.hand_landmarks:
            self._last_positions = {}
            return float("nan")
        total = 0.0
        n = 0
        new_positions = {}
        for i, hand in enumerate(result.hand_landmarks):
            tip = hand[INDEX_FINGERTIP_IDX]
            pos = np.array([tip.x, tip.y])
            new_positions[i] = pos
            if i in self._last_positions:
                total += float(np.linalg.norm(pos - self._last_positions[i]))
                n += 1
        self._last_positions = new_positions
        return total if n > 0 else 0.0

    def reset(self) -> None:
        self._last_positions = {}


def keystroke_impulse_density(events: list, query_timestamps: np.ndarray, sigma_s: float) -> np.ndarray:
    """Smooth keystroke "density" at arbitrary query times: sum of
    Gaussian kernels centred on each keystroke's t_down. Turns a sparse
    impulse train into something correlatable against a continuous
    (irregularly-sampled) hand-activity signal."""
    query_timestamps = np.asarray(query_timestamps, dtype=np.float64)
    if not events:
        return np.zeros(len(query_timestamps))
    t_downs = np.array([e["t_down"] for e in events])
    out = np.zeros(len(query_timestamps))
    for t0 in t_downs:
        out += np.exp(-0.5 * ((query_timestamps - t0) / sigma_s) ** 2)
    return out


def keystroke_hand_coherence(events: list, hand_ts: np.ndarray, hand_activity: np.ndarray,
                              sigma_s: float, lag_max_ms: float, lag_step_ms: float,
                              min_valid_samples: int = 5) -> tuple:
    """Cross-correlates keystroke density against hand activity over a lag
    grid bounded on BOTH sides of zero -- unlike the optical lane's
    0-to-300ms-only search, finger motion and key-down registration are
    both downstream of the same physical press (the motion IS what causes
    the contact), not a one-directional stimulus-then-response
    relationship like light reflection, so the measured velocity peak
    could fall slightly before OR after the electrical key-down event.
    Returns (score, lag_ms), or (nan, nan) if there isn't enough valid
    data -- caller maps that to no_evidence, never to a zero score."""
    hand_ts = np.asarray(hand_ts, dtype=np.float64)
    hand_activity = np.asarray(hand_activity, dtype=np.float64)
    valid = ~np.isnan(hand_activity)
    ts = hand_ts[valid]
    activity = hand_activity[valid]
    if len(activity) < min_valid_samples or np.std(activity) < 1e-9 or not events:
        return float("nan"), float("nan")

    a_centered = activity - activity.mean()
    a_std = np.std(a_centered)

    lags_ms = np.arange(-lag_max_ms, lag_max_ms + 1e-9, lag_step_ms)
    best_score, best_lag = -np.inf, 0.0
    for lag_ms in lags_ms:
        density = keystroke_impulse_density(events, ts - lag_ms / 1000.0, sigma_s)
        d_centered = density - density.mean()
        d_std = np.std(d_centered)
        corr = 0.0 if d_std < 1e-9 else float(np.mean(a_centered * d_centered) / (a_std * d_std))
        if corr > best_score:
            best_score, best_lag = corr, float(lag_ms)
    return best_score, best_lag


