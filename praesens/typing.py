@dataclass
class TypingConfig:
    n_words: int = 5
    hand_model_path: str = "models/hand_landmarker.task"
    min_hand_confidence: float = 0.5
    coherence_sigma_s: float = 0.15
    coherence_lag_max_ms: float = 300.0
    coherence_lag_step_ms: float = 10.0
    min_valid_hand_samples: int = 5
    passive_decay_half_life_s: float = 5.0
    passive_no_evidence_after_s: float = 10.0
    camera_index: int = 0

    @classmethod
    def from_dict(cls, d: dict) -> "TypingConfig":
        return cls(**{k: v for k, v in d.items() if k in cls.__dataclass_fields__})


@dataclass
class TypingResult:
    mode: str  # "active" or "passive"
    status: str  # "ok" | "no_evidence"
    n_keystrokes: int
    n_matched: int | None  # ACTIVE only
    n_expected: int | None  # ACTIVE only, len(phrase)
    inter_key_mean_s: float
    inter_key_std_s: float
    coherence_score: float  # nan if no_evidence
    coherence_lag_ms: float  # nan if no_evidence
    seconds_since_last_keystroke: float  # inf if no keystrokes at all this session
    events: list  # {"t_down","t_up","matched_expected"} -- no characters


def run_typing_session(mode: str, duration_s: float, config: TypingConfig, cap,
                        landmarker=None, expected_phrase: str | None = None) -> TypingResult:
    """Runs one ACTIVE or PASSIVE typing-lane session against an ALREADY-
    OPEN cv2.VideoCapture (never opens its own -- see module docstring).
    ACTIVE requires expected_phrase; PASSIVE ignores it."""
    if mode not in ("active", "passive"):
        raise ValueError(f"mode must be 'active' or 'passive', got {mode!r}")
    if mode == "active" and not expected_phrase:
        raise ValueError("active mode requires expected_phrase")

    own_landmarker = landmarker is None
    if own_landmarker:
        landmarker = create_hand_landmarker(config.hand_model_path, mp_vision.RunningMode.VIDEO,
                                             config.min_hand_confidence)

    capture = KeystrokeCapture(expected_phrase=expected_phrase if mode == "active" else None)
    capture.start()

    tracker = HandActivityTracker()
    hand_ts: list = []
    hand_activity: list = []
    last_ts_ms = -1
    start_time = time.perf_counter()

    import cv2
    import mediapipe as mp

    try:
        while True:
            elapsed = time.perf_counter() - start_time
            if elapsed >= duration_s:
                break
            if mode == "active" and capture.phrase_complete:
                break

            grabbed = cap.grab()
            t = time.perf_counter()
            if not grabbed:
                continue
            ok, frame = cap.retrieve()
            if not ok or frame is None:
                continue

            ts_ms = max(last_ts_ms + 1, int((t - start_time) * 1000))
            last_ts_ms = ts_ms

            rgb = cv2.cvtColor(frame, cv2.COLOR_BGR2RGB)
            mp_image = mp.Image(image_format=mp.ImageFormat.SRGB, data=rgb)
            result = landmarker.detect_for_video(mp_image, ts_ms)
            activity = tracker.process(result)

            hand_ts.append(t)
            hand_activity.append(activity)
    finally:
        capture.stop()
        if own_landmarker:
            landmarker.close()

    events = capture.get_events()
    intervals = capture.inter_key_intervals()

    session_end = start_time + duration_s
    last_kt = capture.last_keystroke_time()
    silence_s = (session_end - last_kt) if last_kt is not None else float("inf")

    n_hand_valid = int(np.sum(~np.isnan(hand_activity))) if hand_activity else 0
    status = compute_typing_status(mode, silence_s, n_hand_valid, config.min_valid_hand_samples,
                                    config.passive_no_evidence_after_s, len(events))

    if status == "ok":
        coherence_score, coherence_lag = keystroke_hand_coherence(
            events, np.array(hand_ts), np.array(hand_activity),
            config.coherence_sigma_s, config.coherence_lag_max_ms, config.coherence_lag_step_ms,
            config.min_valid_hand_samples,
        )
    else:
        coherence_score, coherence_lag = float("nan"), float("nan")

    n_matched = sum(1 for e in events if e["matched_expected"] is True) if mode == "active" else None
    n_expected = len(expected_phrase) if mode == "active" and expected_phrase else None

    return TypingResult(
        mode=mode, status=status, n_keystrokes=len(events),
        n_matched=n_matched, n_expected=n_expected,
        inter_key_mean_s=float(np.mean(intervals)) if len(intervals) else float("nan"),
        inter_key_std_s=float(np.std(intervals)) if len(intervals) else float("nan"),
        coherence_score=coherence_score, coherence_lag_ms=coherence_lag,
        seconds_since_last_keystroke=silence_s,
        events=events,
    )


